import json
from pathlib import Path
R = Path(__file__).resolve().parents[1]
data = json.loads((R / "docs/ARCH_SPECS_raw.json").read_text())
PIPE = {
 "canonical_grid": "dx 0.25 m (X axis), dt 120 s (T axis); tensors are (B, C, T, X); tile 128x256 train, 256x512 overlap 32 infer",
 "input_channels": data[0]["input_desc"],
 "release_pipeline": [
  "RELEASE ens_gen2 (docs/RELEASE_DECISION.md); API dts.infer.release_analyzer() (gen2='on'); rollback gen2='off' = ens_u2ft_tcn_lgbm",
  "raw DTS T(t,x) -> regrid 0.25 m x 120 s -> make_channels -> X (3, T, X)",
  "winner members (parallel): unet_w24 [det0], unet_v810ft w16 [det1], tcn w32 [det2], pixel_lgbm [det3, LightGBM on per-pixel features, not NN]",
  "each -> p_anom = 1 - softmax(bg) (3 classes bg/heat/cool), tiled 256x512 overlap 32",
  "s_winner = mean of 4 score maps (ens_u2ft_tcn_lgbm)",
  "GEN2 U-Net w16 [models_release_gen2/s3_gen2_unet.pt] -> s_gen2 = 1 - softmax(bg)",
  "score = 0.5 * (s_winner + s_gen2); hotness = 0.5 * (h_winner + h_gen2)",
  "threshold at FAR 1e-3 on full v8 val background (all val sequences, synthetic): thr = 0.8580 (old release ens_u2ft_tcn_lgbm: 0.8608)",
  "connected components (zones=cc) -> zones; static=off, mae=off (not calibrated together with gen2)",
  "stage 2: EventNet CNN(32x64 crop)+MLP(scalars) blended 0.5 with LightGBM -> 7 event types",
 ],
 "release_metrics": "ens_gen2: val IoU 0.4106, test 0.4579, v10 0.4576, v11 0.4575 @FAR 1e-3; held-out v8 val (41 seq) +0.018 vs winner; cards 7/15, 0/5 false (old winner: 0.387/0.405, 8/15, 0/5)",
}
out = {"pipeline": PIPE, "models": data,
       "non_nn_boxes": [{"name": "pixel_lgbm (det3)", "type": "LightGBM per-pixel", "file": "models_release/det3_pixel_lgbm.joblib", "status": "RELEASE member"},
                        {"name": "stage-2 LightGBM", "file": "models_release/lgbm.joblib", "status": "RELEASE, blended 0.5 with EventNet"}]}
(R / "docs/ARCH_SPECS.json").write_text(json.dumps(out, indent=1, ensure_ascii=False, default=str))
def f(v):
    if v is None: return ""
    if isinstance(v, (list, tuple)): return "x".join(map(str, v))
    return str(v)
L = ["# Architecture specs of all neural networks (dts_solution)", "",
     "Auto-generated by `scripts/arch_specs.py` + `scripts/arch_specs_md.py` (CPU, weights loaded from the listed checkpoints, param counts from torch). Machine-readable: `docs/ARCH_SPECS.json` (full module trees inside).", "",
     "## Conventions", f"- Grid: {PIPE['canonical_grid']}.", f"- Input 3 channels: {PIPE['input_channels']}.",
     "- Shapes below are for a dummy tile 1x3x128x256 (T=128 rows = 4.3 h, X=256 cols = 64 m); all segmentation nets are fully convolutional.",
     "- PlotNeuralNet: per-layer table gives name, type, in/out ch, out shape (B,C,T,X), kernel, stride, dil, pad; skip links (link to) are listed per model under Skip connections.", "",
     "## Ensemble / pipeline diagram", "```"]
L += ["  " + s for s in PIPE["release_pipeline"]]
L += ["```", "", "```", "X(3,T,X) --+--> unet_w24 ----\\", "           +--> unet_v810ft --+--> mean --> thr@FAR1e-3 (0.861) --> CC / PDRS zones (+STATIC opt.) --> stage2 EventNet+LGBM --> 7 types",
      "           +--> tcn ----------/", "           +--> pixel_lgbm --/   (box, not NN)", "```", "", "## Summary", "",
      "| # | model | status | params | input | output |", "|---|---|---|---|---|---|"]
for i, m in enumerate(data, 1):
    L.append(f"| {i} | {m['name']} | {m['status']} | {m.get('params_total', 'ERR'):,} | {' ; '.join(f(s) for s in m.get('input_shapes', []))} | {json.dumps(m.get('output_shape'))} |")
L += ["| - | pixel_lgbm (det3) | RELEASE member, LightGBM, not NN | - | per-pixel features | p_anom |", ""]
for i, m in enumerate(data, 1):
    L += [f"## {i}. {m['name']}", "", f"- Status: {m['status']}", f"- Checkpoint: {m.get('load')}",
          f"- Params: {m.get('params_total', 0):,} total, {m.get('params_trainable', 0):,} trainable; layer-table sum {sum(r['params'] for r in m.get('layers', [])):,}",
          f"- Input: {m['input_desc']}; shapes {m.get('input_shapes')}", f"- Output: {m.get('output_shape')}" + (f"; head: {m['head']}" if m['head'] else "")]
    if m["flow"]: L.append(f"- Data flow: {m['flow']}")
    if m["skips"]: L.append(f"- Skip connections: " + "; ".join(m["skips"]))
    if m.get("note"): L.append(f"- Note: {m['note']}")
    L += ["", "| # | name | type | in_ch | out_ch | out shape | kernel | stride | dil | pad | params | note |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for j, r in enumerate(m.get("layers", []), 1):
        ic = r.get("in_channels", r.get("in_features", r.get("num_features", "")))
        oc = r.get("out_channels", r.get("out_features", ""))
        L.append(f"| {j} | {r['name']} | {r['type']} | {f(ic)} | {f(oc)} | {f(r.get('out_shape'))} | {f(r.get('kernel_size'))} | {f(r.get('stride'))} | {f(r.get('dilation'))} | {f(r.get('padding'))} | {r['params']} | {r.get('desc', '')} |")
    L += ["", "<details><summary>module tree</summary>", "", "```", m.get("module_tree", m.get("error", "")), "```", "</details>", ""]
(R / "docs/ARCH_SPECS.md").write_text("\n".join(L))
print(len(L))
