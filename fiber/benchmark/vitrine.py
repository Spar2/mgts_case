_REQUIRED = ("name", "task", "family", "input", "time_causal", "serve", "decides", "metric", "protocol")


def rows() -> tuple[dict, ...]:
    return VITRINE


def by_name(name: str) -> dict:
    for row in VITRINE:
        if row["name"] == name:
            return row
    raise KeyError(name)


def check_catalog() -> None:
    names = [row["name"] for row in VITRINE]
    if len(names) != len(set(names)):
        raise ValueError("duplicate vitrine name")
    decisions = [row["decides"] for row in VITRINE]
    if decisions.count("clean") != 1 or decisions.count("status") != 1:
        raise ValueError("expected one clean channel and one status bit")
    for row in VITRINE:
        missing = [key for key in _REQUIRED if key not in row]
        if missing:
            raise ValueError(f"{row.get('name')} missing {missing}")
        if row["serve"] not in {"operational", "api", "scorecard"}:
            raise ValueError(row["name"])
        if row["decides"] not in {"clean", "status", "none"}:
            raise ValueError(row["name"])
        if row["family"] == "research" and row["serve"] != "scorecard":
            raise ValueError(f"{row['name']} research must stay a scorecard")
        if row["serve"] == "operational" and row["decides"] == "none":
            raise ValueError(row["name"])
        if not isinstance(row["time_causal"], bool):
            raise ValueError(row["name"])
        if "кабел" in row["metric"].lower() and "точност" in row["metric"].lower():
            raise ValueError(row["name"])
