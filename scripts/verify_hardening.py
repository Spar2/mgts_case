"""Compare all native records, clean fields, scores and gap-safe events.

The --before path is a previously reproduced f931256 archive, read-only.
No source temperatures or model outputs are generated by this verifier.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from fiber.io import Record
from fiber.pipeline import PipelineConfig


def digest(path): return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--before',type=Path,required=True)
    parser.add_argument('--out',type=Path,default=ROOT/'artifacts/hardening/real-data-verification.json')
    args=parser.parse_args()
    rows=[]
    for name in map(str,range(1,7)):
        before=Record.load(args.before/'artifacts/records'/name)
        after=Record.load(ROOT/'artifacts/records'/name)
        checks={
            'raw_equal':np.array_equal(before.raw_c,after.raw_c,equal_nan=True),
            'valid_equal':np.array_equal(before.valid,after.valid),
            'distance_equal':np.array_equal(before.x_m,after.x_m),
            'time_coordinate_equal':np.array_equal(before.time_s,after.time_s),
            'source_hash_equal':before.source_sha256==after.source_sha256,
            'quality_consistent':np.array_equal(after.valid,after.quality_codes==0),
        }
        for kind,filename in [('denoise','median_x3.npy'),('anomaly','z_spatial.npy')]:
            a=np.load(args.before/f'artifacts/{kind}'/name/filename)
            b=np.load(ROOT/f'artifacts/{kind}'/name/filename)
            checks[f'{kind}_equal']=np.array_equal(a,b,equal_nan=True)
        old_zones=json.loads((args.before/f'artifacts/anomaly/{name}/zones.json').read_text())
        zones=json.loads((ROOT/f'artifacts/anomaly/{name}/zones.json').read_text())
        gap_rows=np.flatnonzero(np.diff(after.time_s)>300)
        across=[z for z in zones if any(z['t_start_s']<=after.time_s[g] and z['t_end_s']>=after.time_s[g+1] for g in gap_rows)]
        checks['no_zones_across_large_time_gaps']=not across
        checks['timezone_unknown_not_fabricated']=not after.tz_missing or all('+' not in t[10:] for t in after.time_iso)
        summary=json.loads((ROOT/f'artifacts/anomaly/{name}/summary.json').read_text())
        rows.append({'record':name,'source_sha256':after.source_sha256,'shape':list(after.raw_c.shape),
                     'checks':checks,'before_zones':len(old_zones),'after_zones':len(zones),
                     'gaps_above300s':len(gap_rows),'zones_across_gaps':len(across),
                     'status':summary['anomaly_status'],'score_coverage':summary['score_coverage'],
                     'quality_counts':{str(code):int(np.count_nonzero(after.quality_codes==code)) for code in (0,1,2,4)}})
    report={'before_commit':'f931256cdaeb371becae0aa390288d128067bca9',
            'records':rows,'all_checks_pass':all(all(r['checks'].values()) for r in rows),
            'manifest':PipelineConfig().manifest(),
            'script_sha256':digest(Path(__file__)),
            'outputs':{f'{name}/{file}':digest(ROOT/'artifacts/anomaly'/name/file) for name in map(str,range(1,7)) for file in ('zones.json','score_available.npy')},
            'expert_confirmed':False,'witnesses_role':'development_regression'}
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({'all_checks_pass':report['all_checks_pass'],'records':[{k:r[k] for k in ('record','before_zones','after_zones','zones_across_gaps','score_coverage')} for r in rows]}))
    if not report['all_checks_pass']: raise SystemExit(1)


if __name__=='__main__': main()
